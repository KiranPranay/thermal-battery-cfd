#!/usr/bin/env python3
"""
generate_initial_fields.py — Generate 0/<region>/T and 0/<region>/p.

v5 changes:
  - Uses config_loader.get_unique_regions() so insulation_A and insulation_B 
    both get initial fields
  - No more local INSULATION_KEYWORDS list (centralized in config_loader)

Patch lists are derived from:
  1. The wedge patches (axis, wedgeFront, wedgeBack) on every region
  2. Inter-region coupled patches (auto-generated by splitMeshRegions)
  3. External patches from config.boundary_conditions

For inter-region patches, we don't know exact names without running splitMeshRegions
first. We use a regex pattern in the BC file ('region_to_.*') that matches any
inter-region patch automatically.

Reads from: config YAML
Writes to:  0/<region>/T and 0/<region>/p for each region
"""

import sys
from pathlib import Path
from config_loader import load_config, get_unique_regions


T_HEADER = '''/*--------------------------------*- C++ -*----------------------------------*\\
| =========                 |                                                 |
| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\\\    /   O peration     | Version:  v2412                                 |
|   \\\\  /    A nd           |                                                 |
|    \\\\/     M anipulation  |                                                 |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       volScalarField;
    location    "0/{region}";
    object      T;
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

dimensions      [0 0 0 1 0 0 0];

internalField   uniform {T_init};

boundaryField
{{
    axis            {{ type empty; }}
    wedgeFront      {{ type wedge; }}
    wedgeBack       {{ type wedge; }}
'''

T_FOOTER = '''
    ".*_to_.*"
    {{
        type            compressible::turbulentTemperatureRadCoupledMixed;
        Tnbr            T;
        kappaMethod     solidThermo;
        qrNbr           none;
        qr              none;
        kappa           none;
        value           uniform {T_init};
    }}
}}

// ************************************************************************* //
'''

EXTERNAL_BC_BLOCK = '''    {patch}
    {{
        type            externalWallHeatFluxTemperature;
        mode            coefficient;
        Ta              uniform {T_amb};
        h               uniform {h};
        kappaMethod     solidThermo;
        kappa           none;
        value           uniform {T_init};
    }}
'''

# Convection + radiation. externalWallHeatFluxTemperature with emissivity
# adds a sigma*emissivity*(T^4 - Ta^4) term to the heat flux (OpenFOAM 2412).
# qr, thicknessLayers, kappaLayers are explicit defaults so the BC dictionary
# is fully specified and resistant to solver default changes.
#
# Emissivity choice (set per-case in config under
# boundary_conditions.external_heat_loss.emissivity):
#   - polished SS304:    eps ~ 0.11   (Jeong 2019 ref [23]; faithful to Jeong)
#   - as-rolled SS304:   eps ~ 0.85   (Chapter 2 parametric study used this)
# The Phase 4 Jeong validation should use 0.11; existing Chapter 2 cases
# (configs/chapter2/ch2_*_radiation.yaml) explicitly pin 0.85 and their
# output files must not be regenerated.
EXTERNAL_BC_BLOCK_RAD = '''    {patch}
    {{
        type            externalWallHeatFluxTemperature;
        mode            coefficient;
        Ta              uniform {T_amb};
        h               uniform {h};
        emissivity      {emissivity};
        thicknessLayers ();
        kappaLayers     ();
        qr              none;
        kappaMethod     solidThermo;
        kappa           none;
        value           uniform {T_init};
    }}
'''

# Adiabatic (zero-flux) patch. Used for Stage 3g axial ends when the
# external BC type is convection_radiation_axial_adiabatic: any of the
# standard external patches (outerCase/bottom/top) not listed in
# applied_to_patches gets this block instead.
ADIABATIC_BC_BLOCK = '''    {patch}
    {{
        type            zeroGradient;
    }}
'''

# The full set of external (non-coupled) patches the blockMeshDict emits.
# Used to determine which of them get an adiabatic zeroGradient BC when a
# subset are listed in applied_to_patches under the axial_adiabatic mode.
STANDARD_EXTERNAL_PATCHES = ('outerCase', 'bottom', 'top')

P_TEMPLATE = '''/*--------------------------------*- C++ -*----------------------------------*\\
| =========                 |                                                 |
| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\\\    /   O peration     | Version:  v2412                                 |
|   \\\\  /    A nd           |                                                 |
|    \\\\/     M anipulation  |                                                 |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       volScalarField;
    location    "0/{region}";
    object      p;
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

dimensions      [1 -1 -2 0 0 0 0];

internalField   uniform 1e5;

boundaryField
{{
    axis            {{ type empty; }}
    wedgeFront      {{ type wedge; }}
    wedgeBack       {{ type wedge; }}
    ".*"            {{ type calculated; value uniform 1e5; }}
}}

// ************************************************************************* //
'''


def _region_owns_external_patches(config, region_name):
    """Return True if this region should emit external-patch BC blocks.

    Historically that's case_ss (Jeong multi-region geometry). For the
    Stage 3g single-region homogenized test there is no case_ss, and the
    outer patches belong to the sole region — detected by (a) case_ss
    is absent from get_unique_regions and (b) region_name is the only
    region present. This keeps the multi-region path bit-identical.
    """
    if region_name == 'case_ss':
        return True
    regions = get_unique_regions(config)
    if 'case_ss' not in regions and len(regions) == 1 and regions[0] == region_name:
        return True
    return False


def generate_T_for_region(config, region_name):
    bc = config['boundary_conditions']
    T_init = bc['initial_temperature_K']

    out = T_HEADER.format(region=region_name, T_init=T_init)

    # External patches: emitted on case_ss for the multi-region case, or
    # on the sole region for a single-region homogenized case.
    if _region_owns_external_patches(config, region_name):
        ext = bc['external_heat_loss']
        # Radiation activated iff config sets a positive emissivity. Absent
        # or zero -> pure convection (bit-identical to pre-radiation output).
        emissivity = ext.get('emissivity', 0.0) or 0.0
        applied = list(ext['applied_to_patches'])
        bc_type = ext.get('type', 'convection_radiation' if emissivity > 0 else 'convection')

        # Stage 3g axial_adiabatic mode: patches NOT listed in
        # applied_to_patches (out of the standard external set) get
        # zeroGradient. In other modes only the listed patches are emitted.
        adiabatic_mode = (bc_type == 'convection_radiation_axial_adiabatic')

        for patch in applied:
            if emissivity > 0:
                out += EXTERNAL_BC_BLOCK_RAD.format(
                    patch=patch,
                    T_amb=ext['T_ambient_K'],
                    h=ext['h_W_per_m2_K'],
                    emissivity=emissivity,
                    T_init=T_init,
                )
            else:
                out += EXTERNAL_BC_BLOCK.format(
                    patch=patch,
                    T_amb=ext['T_ambient_K'],
                    h=ext['h_W_per_m2_K'],
                    T_init=T_init,
                )

        if adiabatic_mode:
            for patch in STANDARD_EXTERNAL_PATCHES:
                if patch not in applied:
                    out += ADIABATIC_BC_BLOCK.format(patch=patch)

    out += T_FOOTER.format(T_init=T_init)
    return out


def generate_P_for_region(config, region_name):
    return P_TEMPLATE.format(region=region_name)


def main():
    if len(sys.argv) < 2:
        sys.exit("Usage: python3 generate_initial_fields.py <config.yaml> [base_dir]")
    
    config_path = sys.argv[1]
    base_dir = Path(sys.argv[2]) if len(sys.argv) > 2 else Path('.')
    
    config = load_config(config_path)
    regions = get_unique_regions(config)
    
    written = 0
    for region in regions:
        # T file
        path = base_dir / '0' / region / 'T'
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, 'w') as f:
            f.write(generate_T_for_region(config, region))
        written += 1
        print(f"Wrote {path}", file=sys.stderr)
        
        # p file
        path = base_dir / '0' / region / 'p'
        with open(path, 'w') as f:
            f.write(generate_P_for_region(config, region))
        written += 1
        print(f"Wrote {path}", file=sys.stderr)
    
    print(f"\nDone: {written} initial field files generated for {len(regions)} regions", file=sys.stderr)


if __name__ == '__main__':
    main()
